/**
 * 数据库方言注册表（国产库兼容的唯一数据源）
 *
 * 设计目标：业务 SQL 保持 MySQL 风格书写，由兼容层按目标驱动自动改写为方言等价写法。
 * 每个方言显式声明「支持的能力」与「不支持的能力」，不静默降级。
 *
 * 驱动分层：
 *   - mysql：mysql2 原生
 *   - postgres / kingbase / opengauss / dameng：走 PG 协议栈 + 本文件方言
 *   - mongodb / influxdb：非关系型占位（现有 SQL 路由不适用）
 */
export const DIALECTS = {
  mysql: {
    name: 'mysql', protocol: 'mysql',
    placeholder: '?', quote: (s) => `\`${s}\``,
    upsert: 'duplicate',      // ON DUPLICATE KEY UPDATE
    ignore: 'native',         // INSERT IGNORE 原生支持
    autoIncrement: 'AUTO_INCREMENT',
    concat: (e) => `GROUP_CONCAT(${e})`,
    now: 'NOW()',
  },
  postgres: {
    name: 'postgres', protocol: 'pg',
    placeholder: '$n', quote: (s) => `"${s}"`,
    upsert: 'conflict',       // ON CONFLICT (...) DO UPDATE SET ...=EXCLUDED....
    ignore: 'conflict-do-nothing',
    autoIncrement: 'GENERATED BY DEFAULT AS IDENTITY',
    concat: (e) => `STRING_AGG(${e}, ',')`,
    now: 'NOW()',
  },
  kingbase: {
    name: 'kingbase', protocol: 'pg',
    placeholder: '$n', quote: (s) => `"${s}"`,
    upsert: 'conflict', ignore: 'conflict-do-nothing',
    autoIncrement: 'GENERATED BY DEFAULT AS IDENTITY',
    concat: (e) => `STRING_AGG(${e}, ',')`, now: 'NOW()',
    note: '人大金仓 KingbaseES（PG 兼容模式）',
  },
  opengauss: {
    name: 'opengauss', protocol: 'pg',
    placeholder: '$n', quote: (s) => `"${s}"`,
    upsert: 'conflict', ignore: 'conflict-do-nothing',
    autoIncrement: 'GENERATED BY DEFAULT AS IDENTITY',
    concat: (e) => `STRING_AGG(${e}, ',')`, now: 'NOW()',
    note: 'openGauss（PG 兼容模式）',
  },
  dameng: {
    name: 'dameng', protocol: 'pg',
    placeholder: '$n', quote: (s) => `"${s}"`,
    upsert: 'conflict', ignore: 'conflict-do-nothing',
    autoIncrement: 'IDENTITY(1,1)',
    concat: (e) => `LISTAGG(${e}, ',') WITHIN GROUP (ORDER BY ${e})`,
    now: 'SYSDATE',
    note: '达梦 DM（PG 兼容模式；部分语法以真机验证为准）',
  },
  mongodb: {
    name: 'mongodb', protocol: 'none', placeholder: null, quote: (s) => s,
    upsert: null, ignore: null, autoIncrement: null,
    note: '非关系型，现有 SQL 路由不适用',
  },
  influxdb: {
    name: 'influxdb', protocol: 'none', placeholder: null, quote: (s) => s,
    upsert: null, ignore: null, autoIncrement: null,
    note: '时序库，现有 SQL 路由不适用',
  },
};

export const PG_DRIVERS = ['postgres', 'kingbase', 'opengauss', 'dameng'];
export const ALL_DRIVERS = Object.keys(DIALECTS);

export function getDialect(driver) {
  return DIALECTS[String(driver || '').toLowerCase()] || null;
}

/**
 * 各表唯一键（冲突目标）：MySQL 的 ON DUPLICATE KEY 不需要指定，PG 系必须显式声明。
 * 自动改写时按表名查此表生成 ON CONFLICT (cols)。
 * 未登记的表不会静默降级——transformSql 会抛出明确错误，提示补登记。
 */
export const UPSERT_KEYS = {
  dict_item_i18n: ['dictItemId', 'lang'],
  message_read_receipts: ['messageId', 'username'],
  role_data_scope_rules: ['role'],
  notifications_reads: ['notificationId', 'username'],
  idempotency_keys: ['idempotencyKey', 'endpoint'],
  app_configs: ['configKey', 'env'],
  data_classification: ['tableName', 'columnName'],
  user_totp: ['username'],
  users: ['username'],
  roles: ['name'],
  departments: ['name'],
  dict_items: ['code'],
  schema_migrations: ['filename'],
};

export function upsertKeysFor(table) {
  return UPSERT_KEYS[String(table || '').replace(/^["`]|["`]$/g, '').toLowerCase()]
    || UPSERT_KEYS[table]
    || null;
}

export default getDialect;
