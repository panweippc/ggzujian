/**
 * 国产库 DDL 生成器 + 静态兼容扫描 的单元验证
 */
import { describe, it, expect } from 'vitest';
import { convertScript, generateDialectSql } from '../scripts/generate-dialect-ddl.mjs';
import { getDialect, PG_DRIVERS, UPSERT_KEYS, upsertKeysFor } from '../services/dialects.js';
import { transformSql } from '../services/pg-compat.js';

describe('方言注册表', () => {
  it('四种 PG 系驱动各有独立方言', () => {
    for (const d of PG_DRIVERS) {
      const dialect = getDialect(d);
      expect(dialect).toBeTruthy();
      expect(dialect.protocol).toBe('pg');
      expect(dialect.upsert).toBe('conflict');
    }
    expect(getDialect('dameng').autoIncrement).toContain('IDENTITY');
    expect(getDialect('postgres').autoIncrement).toContain('IDENTITY');
  });

  it('所有使用 upsert 的业务表都已登记唯一键', () => {
    for (const t of ['dict_item_i18n', 'app_configs', 'data_classification', 'notifications_reads', 'schema_migrations']) {
      expect(upsertKeysFor(t)).toBeTruthy();
      expect(upsertKeysFor(t).length).toBeGreaterThan(0);
    }
  });
});

describe('DDL 生成', () => {
  it('MySQL 类型/选项被转换为 PG 等价写法', () => {
    const mysql = `CREATE TABLE IF NOT EXISTS t (\n  id INT AUTO_INCREMENT PRIMARY KEY,\n  name VARCHAR(20) NOT NULL COMMENT '名字',\n  created DATETIME,\n  flag TINYINT(1),\n  INDEX idx_name (name)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;`;
    const pg = convertScript(mysql, getDialect('postgres'));
    expect(pg).toContain('GENERATED BY DEFAULT AS IDENTITY');
    expect(pg).toContain('TIMESTAMP');
    expect(pg).toContain('BOOLEAN');
    expect(pg).not.toMatch(/AUTO_INCREMENT|ENGINE=|DATETIME|`/);
    expect(pg).toContain('CREATE INDEX idx_name ON t (name)');
    expect(pg).toContain('COMMENT ON COLUMN t.name');
  });

  it('四种方言脚本都能生成且无 MySQL 残留', () => {
    for (const driver of PG_DRIVERS) {
      const sql = generateDialectSql(driver);
      expect(sql.length).toBeGreaterThan(1000);
      expect(sql).not.toMatch(/\bAUTO_INCREMENT\b/i);
      expect(sql).not.toMatch(/\bENGINE\s*=\s*InnoDB\b/i);
      expect(sql).not.toMatch(/,\s*\);/); // 无尾随逗号
    }
  });

  it('达梦使用 TEXT 而非 JSONB', () => {
    const dm = generateDialectSql('dameng');
    const pg = generateDialectSql('postgres');
    expect(pg).toContain('JSONB');
    expect(dm).not.toContain('JSONB');
  });
});

describe('运行时改写与 DDL 标识符一致', () => {
  it('upsert 冲突键用小写裸标识符，与 DDL 建列策略一致', () => {
    const r = transformSql('INSERT INTO app_configs (configKey, configValue, env) VALUES (?,?,?) ON DUPLICATE KEY UPDATE configValue=VALUES(configValue)', []);
    expect(r.text).toContain('ON CONFLICT (configkey, env)');
    expect(r.text).toContain('configvalue=EXCLUDED.configvalue');
  });
});
